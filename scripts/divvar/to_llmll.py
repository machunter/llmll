#!/usr/bin/env python3
"""DIV-VAR-1: write the witness table as LLMLL sources.

Every task of divvar_run.build_tasks() (rows 1 to 7 of the table in
image-library-proposal.md Part C, mutants included) becomes one `def`:

* geom.llmll holds offset, row-of, col-of, chan-of, hflip-x and scale-src.
  No `def` in it calls a sibling. at.llmll (hflip-at) and rt.llmll (the three
  round trips) import it, so geom.llmll is verified first.
* Rows 2, 3, 5, 6 and 7 are one module each.
* A mutant is one module: a geom mutant stands alone, an hflip-at mutant
  imports geom. The expected verdict is the exhaustive oracle's
  (divvar_lib.oracle): `verified` for an equivalent body, else `refuted`.
* The refusal scan of row 7 (ground divisors <= 0, rem, quot) is one
  def-shell module each, with the refused term in the post.

It also writes expected.json: per task the file, the function, the module to
verify first, the row, the expected verdict and whether the task is one of the
166 counted ones.

Usage: python3 scripts/divvar/to_llmll.py [outdir]
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import divvar_lib as L  # noqa: E402
import divvar_run as R  # noqa: E402

REPO = os.path.dirname(os.path.dirname(HERE))
DEFAULT_OUT = os.path.join(REPO, "scripts", "tests", "fixtures", "div_var_1")
GEOM = ("offset", "row-of", "col-of", "chan-of", "hflip-x", "scale-src")
NARY = {"and", "or", "+", "*"}
BYTES_OPS = {"bytes-get", "bytes-length"}

# row 2 to 7: (file stem, function) of each original or probe, by its label
PROBES = {
    "scale-src sw=1, post as written": ("r2a", "scale-one"),
    "scale-src sw=1, (= result 0)": ("r2b", "scale-one"),
    "row-of, body (let ((stride (* w c))) (/ i stride))": ("r3", "row-of-stride"),
    "shadow d: post (/ i d), body (let ((d (+ d 1))) (/ i d))": ("r5a", "shadow"),
    "shadow d: post (mod i d), body (let ((d (+ d 1))) (mod i d))": ("r5b", "shadow"),
    "shadow i: post (/ i d), body (let ((i (+ i 1))) (/ i d))": ("r5d", "shadow"),
    "shadow i, equivalent: post (mod i d), body (let ((i (+ i d))) (mod i d)) (info)": ("r5c", "shadow"),
    "pre (=> (>= d 1) (= (/ e d) q))": ("r6a", "guarded"),
    "pre (= (/ e d) q), unguarded": ("r6b", "unguarded"),
    "guarded use: pre (and (>= e 0) (=> (>= d 1) (= (/ e d) q))), post (=> (>= d 1) (>= q 0))": ("r6c", "guarded-use"),
    "edge case 6: (/ x (- 0 w)), pre (>= w 1)": ("r7a", "neg-divisor"),
    "divisor (- w w)": ("r7b", "zero-divisor"),
}
ROUND_TRIPS = {
    "row-of(offset(y,x,k)) = y": "rt-row",
    "col-of(offset(y,x,k)) = x (extra)": "rt-col",
    "chan-of(offset(y,x,k)) = k (extra)": "rt-chan",
}
# row 7, no solver: (term, construct)
REFUSALS = [
    ("(/ x 0)", "nonlinear:/"), ("(mod x 0)", "nonlinear:mod"), ("(/ x -2)", "nonlinear:/"),
    ("(mod x -3)", "nonlinear:mod"), ("(/ x (- 0 2))", "nonlinear:/"), ("(mod x (- 2 2))", "nonlinear:mod"),
    ("(/ x (/ 1 2))", "nonlinear:/"), ("(rem x d)", "nonlinear:rem"), ("(quot x d)", "nonlinear:quot"),
]


def render(t, imported):
    """A script s-expression as LLMLL text: n-ary and/or/+/* nest to the right, a geom call is qualified
    when the module imports geom, and the script's (let ((x e)) b) is LLMLL's (let [(x e)] b)."""
    if isinstance(t, str):
        return t
    op, *a = t
    if op == "let":
        bs = " ".join(f"({nm} {render(ex, imported)})" for nm, ex in a[0])
        return f"(let [{bs}] {render(a[1], imported)})"
    if op in NARY and len(a) > 2:
        return render([op, a[0], [op] + a[1:]], imported)
    head = "geom." + op if imported and op in L.CALLEES else op
    return "(" + " ".join([head] + [render(x, imported) for x in a]) + ")"


def definition(name, f, body, imported=False, form="def"):
    sorts = f.get("sorts") or {}
    params = " ".join(f"{p}: {'bytes' if sorts.get(p) == 'bytes' else 'int'}" for p in f["params"].split())
    lines = [f"  ({form} {name} [{params}] -> int"]
    if f.get("pre"):
        lines.append(f"    (pre {render(L.P(f['pre']), imported)})")
    lines.append(f"    (post {render(L.P(f['post']), imported)})")
    lines.append(f"    {render(L.P(body), imported)})")
    return "\n".join(lines)


def module(name, note, exports, defs, imports=()):
    head = [f";; DIV-VAR-1 {note}", ";; Generated by scripts/divvar/to_llmll.py.", f"(module {name}"]
    head += [f"  (import {i})" for i in imports]
    head.append(f"  (export {' '.join(exports)})")
    return "\n".join(head) + "\n" + "\n".join(defs) + ")\n"


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_OUT
    os.makedirs(out, exist_ok=True)

    def write(stem, text):
        with open(os.path.join(out, stem + ".llmll"), "w") as f:
            f.write(text)

    write("geom", module("geom", "row 1: the geometry functions. No def calls a sibling.", GEOM,
                         [definition(n, L.FUNS[n], L.FUNS[n]["body"]) for n in GEOM]))
    at = L.FUNS["hflip-at"]
    write("at", module("at", "row 1: hflip-at over geom.", ["hflip-at"],
                       [definition("hflip-at", at, at["body"], imported=True)], ["geom"]))

    R.TASKS.clear()
    R.build_tasks()
    tasks, round_trips, counter = {}, [], {}
    for t in R.TASKS:
        row, label = t["row"], t["label"]
        entry = dict(row=row, expected=t["expected"].split("|"), kind=t["kind"], counted=t["count"], first=None)
        if t["kind"] == "mutant":
            n = counter[label] = counter.get(label, 0) + 1
            stem = f"m-{label}-{n:02d}"
            imported = label == "hflip-at"
            write(stem, module(stem, f"row 1: mutant {n} of {label}, operator {t['op']}. Oracle: {t['oracle']}.", [label],
                               [definition(label, t["f"], t["body"], imported)], ["geom"] if imported else ()))
            entry.update(file=stem + ".llmll", id=label, op=t["op"], body=t["body"], first="geom.llmll" if imported else None)
            tasks[stem] = entry
        elif row == "1":
            entry.update(file="at.llmll" if label == "hflip-at" else "geom.llmll", id=label,
                         first="geom.llmll" if label == "hflip-at" else None)
            tasks[label] = entry
        elif label in ROUND_TRIPS:
            name = ROUND_TRIPS[label]
            round_trips.append(definition(name, t["f"], t["body"], imported=True))
            entry.update(file="rt.llmll", id=name, first="geom.llmll")
            tasks[name] = entry
        else:
            stem, name = PROBES[label]
            write(stem, module(stem, f"row {row}: {label}.", [name], [definition(name, t["f"], t["body"])]))
            entry.update(file=stem + ".llmll", id=name)
            if not t["count"]:
                entry["expected"] = ["fallback"]   # row 5c: a true claim the facts do not reach
            tasks[stem] = entry
    write("rt", module("rt", "row 4: the three round trips over geom.", list(ROUND_TRIPS.values()), round_trips, ["geom"]))

    refusals = {}
    for i, (term, construct) in enumerate(REFUSALS, 1):
        stem = f"r7-refuse-{i}"
        f = dict(params="x d", pre="(>= d 1)", post=f"(>= {term} 0)", sorts={})
        write(stem, module(stem, f"row 7: {term} is refused with no solver call.", ["refused"],
                           [definition("refused", f, "0", form="def-shell")]))
        # `rem` and `quot` are not functions of the surface, so `llmll check`
        # refuses them before the emitter's refusal scan can
        unknown = term[1:].split()[0] in ("rem", "quot")
        refusals[stem] = dict(file=stem + ".llmll", id="refused", term=term, construct=construct,
                              outcome="unknown-function" if unknown else "fallback")

    counted = [t for t in tasks.values() if t["counted"]]
    summary = dict(tasks=len(tasks), counted=len(counted), mutants=sum(t["kind"] == "mutant" for t in tasks.values()),
                   equivalent_mutants=sum(t["kind"] == "mutant" and t["expected"] == ["verified"] for t in tasks.values()),
                   refusals=len(refusals), source="scripts/divvar/divvar_run.py build_tasks(), divvar_lib.oracle")
    with open(os.path.join(out, "expected.json"), "w") as f:
        json.dump(dict(summary=summary, tasks=tasks, refusals=refusals), f, indent=1, sort_keys=True)
        f.write("\n")
    print(json.dumps(summary))


if __name__ == "__main__":
    main()
