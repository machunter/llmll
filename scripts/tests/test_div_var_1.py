@needs_solver
@pytest.mark.parametrize("name", sorted(EXPECTED["refusals"]))
def test_dv_w5_refusals_send_no_constraint(tmp_path: Path, name: str) -> None:
    """Row 7: a ground divisor <= 0 falls back with its construct and the solver
    gets no constraint. `rem` and `quot` are not functions of the surface."""
    r = EXPECTED["refusals"][name]
    shutil.copy(FIXTURES / r["file"], tmp_path / r["file"])
    p = _run(tmp_path, "--json", "verify", r["file"])
    doc = _last_json(p.stdout)
    if r["outcome"] == "unknown-function":
        assert p.returncode == 1, p.stdout
        assert f"call to unknown function '{r['construct'].split(':')[1]}'" in p.stdout, p.stdout
        return
    assert p.returncode == 0, p.stdout
    assert doc["body_fallback_causes"] == {"refused": "contract-post-outside-fragment"}, doc
    assert doc["body_fallback_constructs"] == {"refused": [r["construct"]]}, doc
    q = _run(tmp_path, "verify", r["file"])
    fq = re.search(r"\.fq written to (\S+\.fq)", q.stdout)
    assert fq, q.stdout
    assert "constraint:" not in Path(fq.group(1)).read_text()


@needs_solver
@pytest.mark.parametrize("op", ["rem", "/", "mod"])
def test_dv_rem_stays_refused_in_json_ast(tmp_path: Path, op: str) -> None:
    """JSON-AST spells an operator as `op`: `/` and `mod` by a variable verify,
    and `rem` is not an operator. The emitter's own refusal, nonlinear:rem, is
    the hspec cell DV-E-2."""
    v = lambda n: {"kind": "var", "name": n}
    e = lambda o, *a: {"kind": "op", "op": o, "args": list(a)}
    lit = lambda k: {"kind": "lit-int", "value": k}
    mod = {"schemaVersion": "0.15.0", "llmll_version": "0.42.0", "statements": [
        {"kind": "export", "names": ["f"]},
        {"kind": "def-shell", "name": "f",
         "params": [{"name": n, "param_type": {"kind": "primitive", "name": "int"}} for n in "xd"],
         "return_type": {"kind": "primitive", "name": "int"},
         "pre": e(">=", v("d"), lit(1)),
         "post": e("=", v("result"), e(op, v("x"), v("d"))),
         "body": e(op, v("x"), v("d"))}]}
    (tmp_path / "f.ast.json").write_text(json.dumps(mod))
    p = _run(tmp_path, "--json", "verify", "--trust-report", "f.ast.json")
    doc = _last_json(p.stdout)
    if op == "rem":
        assert p.returncode == 1, p.stdout
        assert "unknown operator 'rem'" in [d["message"] for d in doc["diagnostics"]], p.stdout
    else:
        assert _verdict(doc, "f") == "verified", p.stdout


@needs_solver
def test_dv_n1_core_syntax_and_an_unproved_divisor(tmp_path: Path) -> None:
    """A variable divisor passes check in a `def` body and guard; a ground divisor
    <= 0 does not; a `def` whose divisor is not proved is refuted, never verified."""
    def src(name: str, text: str) -> str:
        (tmp_path / name).write_text(text)
        return name
    ok = src("ok.llmll", "(module ok (export f g)\n"
             "  (def f [w: int i: int] -> int (pre (>= w 1)) (post (= result (/ i w))) (/ i w))\n"
             "  (def g [w: int i: int] -> int (pre (>= w 1)) (post (>= result 0)) (if (> (/ i w) 2) 1 0)))\n")
    p = _run(tmp_path, "--json", "verify", "--trust-report", ok)
    assert p.returncode == 0, p.stdout
    assert [_verdict(_last_json(p.stdout), f) for f in "fg"] == ["verified", "verified"]
    z = src("z.llmll", "(module z (export f)\n  (def f [x: int] -> int (/ x 0)))\n")
    p = _run(tmp_path, "check", z)
    assert p.returncode == 1 and "non-core syntax" in p.stdout + p.stderr, p.stdout + p.stderr
    # the true post does not help: the divisor is not proved
    for body in ("(/ i w)", "(mod i w)", "(if (> (+ 1 (mod i w)) 2) 1 0)"):
        u = src("u.llmll", f"(module u (export f)\n  (def f [w: int i: int] -> int (post (or (>= result 0) (< result 0))) {body}))\n")
        p = _run(tmp_path, "--json", "verify", "--trust-report", u)
        doc = _last_json(p.stdout)
        assert p.returncode == 1 and _verdict(doc, "f") == "refuted", (body, p.stdout)


@needs_solver
def test_dv_shadowed_mod_is_never_the_builtin(tmp_path: Path) -> None:
    """A function-typed parameter named `mod`: no claim about it is verified by
    the division theorems, in the body or in a clause."""
    for post, body in (("(= result (mod x d))", "(mod x d)"), ("(>= (mod x d) 0)", "0")):
        (tmp_path / "s.llmll").write_text(
            "(module s (export f)\n  (def-shell f [mod: (fn [int int] -> int) x: int d: int] -> int\n"
            f"    (pre (>= d 1)) (post {post}) {body}))\n")
        p = _run(tmp_path, "--json", "verify", "--trust-report", "s.llmll")
        assert _verdict(_last_json(p.stdout), "f") == "fallback", p.stdout


@needs_solver
def test_dv_e1_row_of_example_mutant_prints_a_validated_model(tmp_path: Path, geom_dir: Path) -> None:
    name = next(n for n, t in TASKS.items() if t["kind"] == "mutant" and t["id"] == "row-of" and t["body"] == "(/ i w)")
    p = _run(_work(tmp_path, geom_dir, name), "verify", TASKS[name]["file"])
    assert p.returncode == 1, p.stdout + p.stderr
    lines = [ln.strip() for ln in p.stdout.splitlines() if "VC counterexample:" in ln]
    assert lines, p.stdout
    m = re.fullmatch(r"VC counterexample: ((?:\S+=-?\d+ ?)+)\. Callee results in it are assumed, not computed\.",
                     lines[0])
    assert m, lines[0]
    vals = {k: int(x) for k, x in (kv.split("=") for kv in m.group(1).split())}
    w, c, h, i, r = (vals[k] for k in ("w", "c", "h", "i", "result"))
    assert w >= 1 and c >= 1 and h >= 1 and 0 <= i < w * h * c, vals
    assert r == i // w and not (r == i // (w * c) and 0 <= r < h), vals


