"""DIV-VAR-1: `(/ e d)` and `(mod e d)` with a divisor that is not a constant, end to end.

Design: docs/design/image-library-proposal.md (Rev 4a), Part C. Each distinct
normal-form pair (e, d) becomes two symbols `div##k` and `mod##k`, with a
fixed set of division theorems (D0, G, D4). Each evaluation owes `d >= 1`: a
`call-pre:/` or `call-pre:mod` obligation in a body, a `wd-pre` or `wd-post`
entry in a clause. An UNSAFE answer on such a constraint is a disproof only
after the native recheck finds a model that Haskell `div` and `mod` confirm.

What a pass here means:

* W1 to W5 are the witness table of Part C through `llmll --json verify
  --trust-report`, one file at a time, each in its own temporary folder (no
  sidecar is written into the repo). The sources are generated by
  scripts/divvar/to_llmll.py, and expected.json holds each verdict: rows 1 to 7
  and the mutants, whose expected verdict an exhaustive oracle decided with
  Haskell semantics. W4 is a sample of the `hflip-at` mutants; the whole table
  (166 tasks) runs with scripts/divvar/verify_all.py.
* E1 and E2 are the messages of a refutation and of edge case 6.
* N1: a variable divisor is core syntax in a `def`; a `def` whose `d >= 1` is
  not proved is never verified; a ground divisor <= 0 and `rem` stay refused.
* The fixtures of the hspec suite (witnesses.json) and of this file are what
  the committed scripts write.

Every test that verifies needs a built llmll (LLMLL_BIN), liquid-fixpoint and
z3 on PATH.
"""

from __future__ import annotations

import json
import os
import re
import shlex
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
FIXTURES = REPO_ROOT / "scripts" / "tests" / "fixtures" / "div_var_1"
HSPEC_FIXTURE = REPO_ROOT / "compiler" / "test" / "fixtures" / "div_var_1" / "witnesses.json"
DIVVAR = REPO_ROOT / "scripts" / "divvar"
EXPECTED = json.loads((FIXTURES / "expected.json").read_text())
TASKS = EXPECTED["tasks"]
TIMEOUT_S = 300

solver = [
    pytest.mark.skipif(not os.environ.get("LLMLL_BIN"), reason="set LLMLL_BIN to a built llmll"),
    pytest.mark.skipif(
        shutil.which("liquid-fixpoint") is None and shutil.which("fixpoint") is None,
        reason="needs liquid-fixpoint on PATH",
    ),
    pytest.mark.skipif(shutil.which("z3") is None, reason="the native recheck needs z3 on PATH"),
]


def needs_solver(f):
    for m in solver:
        f = m(f)
    return f


def _llmll() -> list[str]:
    return shlex.split(os.environ["LLMLL_BIN"])


def _run(cwd: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(_llmll() + list(args), cwd=str(cwd), capture_output=True,
                          text=True, timeout=TIMEOUT_S)


def _last_json(stdout: str) -> dict:
    lines = [ln for ln in stdout.splitlines() if ln.strip()]
    return json.loads(lines[-1])


def _verdict(doc: dict, fid: str) -> str:
    """verified, refuted, ill-defined, fallback or other; refuted comes before ill-defined."""
    if fid in (doc.get("abstraction_fallback") or {}) or fid in (doc.get("body_fallback") or []):
        return "fallback"
    tr = doc.get("trust_report") or {}
    tr = json.loads(tr) if isinstance(tr, str) else tr
    if any(e.get("name") == fid and e.get("refuted") for e in tr.get("entries", [])):
        return "refuted"
    if fid in (doc.get("ill_defined") or []):
        return "ill-defined"
    if fid in (doc.get("body_faithful") or []) and doc.get("solver_verdict") == "safe":
        return "verified"
    return "other:" + str(doc.get("solver_verdict"))


@pytest.fixture(scope="module")
def geom_dir(tmp_path_factory) -> Path:
    """geom.llmll verified once; an importer gets a copy of it and of its sidecar."""
    d = tmp_path_factory.mktemp("geom")
    shutil.copy(FIXTURES / "geom.llmll", d / "geom.llmll")
    p = _run(d, "--json", "verify", "geom.llmll")
    assert p.returncode == 0, p.stdout + p.stderr
    return d


def _work(tmp_path: Path, geom_dir: Path, name: str) -> Path:
    t = TASKS[name]
    work = tmp_path / name
    work.mkdir()
    shutil.copy(FIXTURES / t["file"], work / t["file"])
    if t["first"]:
        for f in ("geom.llmll", "geom.llmll.verified.json"):
            shutil.copy(geom_dir / f, work / f)
    return work


def _table(tmp_path: Path, geom_dir: Path, names: list[str]) -> None:
    """Every named task has its expected verdict, and its exit code agrees."""
    mismatches = []
    for name in names:
        t = TASKS[name]
        p = _run(_work(tmp_path, geom_dir, name), "--json", "verify", "--trust-report", t["file"])
        v = _verdict(_last_json(p.stdout), t["id"])
        want_exit = 1 if v in ("refuted", "ill-defined") else 0
        if v not in t["expected"] or p.returncode != want_exit:
            mismatches.append((name, v, p.returncode, t["expected"]))
    assert mismatches == [], mismatches


def _mutants(prefix: str) -> list[str]:
    return sorted(n for n, t in TASKS.items() if t["kind"] == "mutant" and t["id"] == prefix)


def test_dv_fixtures_are_what_the_scripts_write(tmp_path: Path) -> None:
    """witnesses.json (hspec) and the .llmll fixtures, byte for byte."""
    out = tmp_path / "witnesses.json"
    p = subprocess.run([sys.executable, str(DIVVAR / "export_witnesses.py"), str(out)],
                       capture_output=True, text=True, timeout=TIMEOUT_S)
    assert p.returncode == 0, p.stdout + p.stderr
    assert out.read_bytes() == HSPEC_FIXTURE.read_bytes()
    fx = tmp_path / "fx"
    p = subprocess.run([sys.executable, str(DIVVAR / "to_llmll.py"), str(fx)],
                       capture_output=True, text=True, timeout=TIMEOUT_S)
    assert p.returncode == 0, p.stdout + p.stderr
    want = {f.name: f.read_bytes() for f in FIXTURES.iterdir() if f.suffix in (".llmll", ".json") and ".verified" not in f.name}
    got = {f.name: f.read_bytes() for f in fx.iterdir()}
    assert sorted(got) == sorted(want)
    assert [n for n in got if got[n] != want[n]] == []
    s = EXPECTED["summary"]
    assert (s["counted"], s["mutants"], s["equivalent_mutants"], s["refusals"]) == (166, 147, 4, 9), s


