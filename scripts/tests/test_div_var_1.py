"""DIV-VAR-1: `(/ e d)` and `(mod e d)` with a divisor that is not a constant, end to end.

Design: docs/design/image-library-proposal.md (Rev 4a), Part C. Each distinct
normal-form pair (e, d) becomes two symbols `div##k` and `mod##k`, with a
fixed set of division theorems (D0, G, D4). Each evaluation owes `d >= 1`: a
`call-pre:/` or `call-pre:mod` obligation in a body, a `wd-pre` or `wd-post`
entry in a clause. An UNSAFE answer on such a constraint is a disproof only
after the native recheck finds a model that Haskell `div` and `mod` confirm.

What a pass here means:

* W1 to W5 are the witness table of Part C through `llmll --json verify
  --trust-report`, one file at a time, each in its own temporary folder (no
  sidecar is written into the repo). The sources are generated by
  scripts/divvar/to_llmll.py, and expected.json holds each verdict: rows 1 to 7
  and the mutants, whose expected verdict an exhaustive oracle decided with
  Haskell semantics. W4 is a sample of the `hflip-at` mutants; the whole table
  (166 tasks) runs with scripts/divvar/verify_all.py.
* E1 and E2 are the messages of a refutation and of edge case 6.
* N1: a variable divisor is core syntax in a `def`; a `def` whose `d >= 1` is
  not proved is never verified; a ground divisor <= 0 and `rem` stay refused.
* The fixtures of the hspec suite (witnesses.json) and of this file are what
  the committed scripts write.
* E3 to E6 are the other callers (step 2). `patch` rejects a wrong fill of
  `row-of`, and names the divisor when its `d >= 1` is not proved;
  `diverge-report` puts the wrong fill under `refuted`; one `--cdp` run kills
  every mutant of the `row-of` post (CDP runs must not overlap,
  CDP-FQ-RACE-1); a replay of a division refutation reproduces and reruns the
  native recheck, also on a VC whose only emitter symbols are `div##k` and
  `mod##k`.
* T1: the trust report names the ground-fact family `division-facts`.
* X1: a bytes-tabulate over `at.hflip-at` verifies its length post, and the
  generator's byte-range constraint (T3) holds division facts at the index.

Every test that verifies needs a built llmll (LLMLL_BIN), liquid-fixpoint and
z3 on PATH.
"""

