#!/usr/bin/env python3
"""MUL-VAR-1 Step 0: write the 132 rev3.py witnesses as LLMLL sources.

Each row T(group, name, vars, hyps, goal[, truth[, sorts]]) of rev3.py becomes
one file

    (module <id> (export <id>)
      (def-shell <id> [<v>: int ...] -> int
        (pre (and hyps...))
        (post goal)
        0))

The post never names `result`, so the body VC is hyps => goal.

A row with a `sorts` argument (bytes, Str, intmap, strmap) has no mechanical
translation: LLMLL has no unsized bytes type and no whole-array `=`. Those
fixtures are hand-written in the fixture folder, each with a comment naming
the rev3.py row it restates. This script checks that each one exists and does
not overwrite it.

It also writes expected.json, the design verdict per witness, from the tables
of docs/design/mul-var-proposal.md (measurement 1): every true witness is
`verified` except W14, W23, W25 and Y5 (fallback); every false witness is
`refuted`.

Usage: python3 scripts/mulvar/to_llmll.py [outdir]
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import rev3  # noqa: E402

REPO = os.path.dirname(os.path.dirname(HERE))
DEFAULT_OUT = os.path.join(REPO, "scripts", "tests", "fixtures", "mul_var_1")

# design "Measurements", table 1: the four true witnesses B does not prove
DESIGN_MISSES = {"W14", "W23", "W25", "Y5"}

# Hand-written fixtures and why each is not a mechanical translation.
# "faithful": the LLMLL source states the same VC up to the emitter's own
# encoding. Otherwise "why" names each departure.
HAND = {
    "Q4": dict(faithful=False, why="bytes[n] fixes bytesLen(b) to a literal (LLMLL has no unsized bytes); here bytes[64]"),
    "Q7": dict(faithful=False, why="bytes[64] fixes bytesLen(b); the read in the pre carries a CLAUSE-WELLDEF-1 definedness obligation"),
    "N4": dict(faithful=False, why="bytes[64] fixes bytesLen(b)"),
    "N5": dict(faithful=False, why="bytes[64] fixes bytesLen(b); the read in the pre is out of bounds exactly in the counterexample, so LLMLL may report ill-defined rather than refuted"),
    "K8": dict(faithful=False, why="bytes[64] fixes bytesLen(b)"),
    "KF4": dict(faithful=False, why="bytes[64] fixes bytesLen(b)"),
    "B1": dict(faithful=False, why="bytes[64] fixes bytesLen(b); i gains 0 <= i < 64 so the read in the pre is defined"),
    "B2": dict(faithful=False, why="whole-bytes = does not reflect: c is inlined as (bytes-set b 0 7) and the length-preservation hypothesis is the emitter's own fact; bytes[64]"),
    "B3": dict(faithful=True, why="string-length is the strLen measure"),
    "B4": dict(faithful=False, why="the two-array map (hs, vl) is one map[int,int]; whole-map = does not reflect, so hs2/vl2 are inlined as (map-put m (* y w) v) and select hs2 _ = 1 is map-has"),
    "BF1": dict(faithful=False, why="as B2: c inlined, bytes[64]"),
    "BF2": dict(faithful=False, why="c inlined; bytes[64]; adds bytesLen(b) = w*h so the read in the pre is defined"),
    "BF3": dict(faithful=False, why="c inlined; bytes[64]"),
    "BF4": dict(faithful=True, why="string-length is the strLen measure"),
    "BF5": dict(faithful=False, why="as B4: one map[int,int], map-put inlined, presence via map-has"),
    "BF6": dict(faithful=True, why="string = and string-length; depends on string variable equality reflecting"),
    "BF7": dict(faithful=True, why="string != and string-length; depends on string variable disequality reflecting"),
    "BF8": dict(faithful=False, why="the string-valued array is a map[int,string]; map-get needs presence, so map-has mv k and map-has mv j are added before the reads"),
    "BF9": dict(faithful=False, why="bytes[64] fixes bytesLen(b); v = (bytes-get b src) is dropped because its read is out of bounds exactly in the counterexample (v is not in the goal)"),
}

NARY = {"and", "or", "+", "*"}


def short(name):
    return name.split()[0]


def ident(name):
    return "mv-" + short(name).lower()


def render(t):
    """rev3 s-expression to LLMLL text. n-ary and/or/+/* nest to the right."""
    if isinstance(t, str):
        return t
    op, *a = t
    if op in NARY and len(a) > 2:
        return render([op, a[0], [op] + a[1:]])
    return "(" + " ".join([op] + [render(x) for x in a]) + ")"


def conj(hs):
    if not hs:
        return None
    if len(hs) == 1:
        return render(hs[0])
    return render(["and"] + list(hs))


def emit(rec):
    vs, hyps, goal = rec["w"]
    name = rec["name"]
    i = ident(name)
    order = rec["vs_order"]
    params = " ".join(f"{v}: int" for v in order)
    lines = [
        f";; MUL-VAR-1 witness {short(name)}: rev3.py row \"{name}\", group {rec['group']}, truth {'true' if rec['truth'] else 'false'}.",
        ";; Generated by scripts/mulvar/to_llmll.py. The post never names result, so the body VC is pre => post.",
        f"(module {i}",
        f"  (export {i})",
        f"  (def-shell {i} [{params}] -> int",
    ]
    p = conj(hyps)
    if p is not None:
        lines.append(f"    (pre {p})")
    lines.append(f"    (post {render(goal)})")
    lines.append("    0))")
    return "\n".join(lines) + "\n"


def var_order(rec):
    """The row's variable list in written order (rev3 keeps a set)."""
    src = rec["vs_text"]
    return src.split()


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_OUT
    os.makedirs(out, exist_ok=True)
    # rev3.W turns the variable string into a set; recover the written order from the source
    import inspect
    srcs = {}
    text = inspect.getsource(rev3)
    for line in text.splitlines():
        line = line.strip()
        if line.startswith('T("'):
            parts = line.split('"')
            # T("G", "name", "vars", ...
            srcs[parts[3]] = parts[5]
    for rec in rev3.TBL:
        if rec["name"] in srcs:
            rec["vs_text"] = srcs[rec["name"]]
        elif short(rec["name"]) == "K13":
            rec["vs_text"] = " ".join([f"a{i}" for i in range(9)] + [f"p{i}" for i in range(9)] + ["r"])
        else:
            raise SystemExit("no variable text for " + rec["name"])
        rec["vs_order"] = var_order(rec)
        if set(rec["vs_order"]) != rec["w"][0] and set(rev3.PV.split()) == rec["w"][0]:
            rec["vs_order"] = rev3.PV.split()  # PF, PF2 pass the PV constant
        assert set(rec["vs_order"]) == rec["w"][0], rec["name"]
    expected = {}
    written = hand = 0
    for rec in rev3.TBL:
        s = short(rec["name"])
        fn = os.path.join(out, ident(rec["name"])[3:] + ".llmll")
        entry = dict(
            id=ident(rec["name"]),
            file=os.path.basename(fn),
            group=rec["group"],
            truth=rec["truth"],
            design_verdict=("fallback" if s in DESIGN_MISSES else "verified") if rec["truth"] else "refuted",
            rev3_row=rec["name"],
        )
        if rec["sorts"]:
            if s not in HAND:
                raise SystemExit(f"{s}: has sorts but no hand-written entry")
            if not os.path.exists(fn):
                raise SystemExit(f"{s}: hand-written fixture {fn} is missing")
            entry.update(source="hand", faithful=HAND[s]["faithful"], note=HAND[s]["why"])
            hand += 1
        else:
            with open(fn, "w") as f:
                f.write(emit(rec))
            entry.update(source="generated", faithful=True)
            written += 1
        expected[s] = entry
    tr = [e for e in expected.values() if e["truth"]]
    fa = [e for e in expected.values() if not e["truth"]]
    summary = dict(
        witnesses=len(expected),
        true=len(tr),
        false=len(fa),
        true_verified=sum(e["design_verdict"] == "verified" for e in tr),
        false_refuted=sum(e["design_verdict"] == "refuted" for e in fa),
        design_misses=sorted(DESIGN_MISSES),
        source="docs/design/mul-var-proposal.md, Measurements, table 1 (Rev 3a)",
    )
    with open(os.path.join(out, "expected.json"), "w") as f:
        json.dump(dict(summary=summary, witnesses=expected), f, indent=2, sort_keys=True)
        f.write("\n")
    print(f"generated {written}, hand-written {hand}, total {len(expected)}; "
          f"true {summary['true']} ({summary['true_verified']} verified by design), false {summary['false']}")


if __name__ == "__main__":
    main()
